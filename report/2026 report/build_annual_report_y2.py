def render_gantt(doc, g):
    months = g['months']; nm = len(months)
    ncol = 2 + nm + 1
    table = doc.add_table(rows=2 + len(g['rows']), cols=ncol); table.style = 'Table Grid'; table.alignment = WD_TABLE_ALIGNMENT.CENTER
    hdr = table.rows[0].cells; hdr2 = table.rows[1].cells
    cell_text(hdr[0], '일련\n번호', 8, True, 'center', 'D9D9D9'); cell_text(hdr[1], '개발 내용', 8, True, 'center', 'D9D9D9')
    cell_text(hdr[2], g['period'], 8, True, 'center', 'D9D9D9'); cell_text(hdr[ncol - 1], '달성도\n(%)', 8, True, 'center', 'D9D9D9')
    for i, m in enumerate(months): cell_text(hdr2[2 + i], m, 8, True, 'center', 'D9D9D9')
    table.cell(0, 0).merge(table.cell(1, 0)); table.cell(0, 1).merge(table.cell(1, 1)); table.cell(0, ncol - 1).merge(table.cell(1, ncol - 1))
    table.cell(0, 2).merge(table.cell(0, 1 + nm))
    for r, (no, name, plan, done, ach) in enumerate(g['rows']):
        cells = table.rows[2 + r].cells
        cell_text(cells[0], no, 8, False, 'center'); cell_text(cells[1], name, 8); cell_text(cells[ncol - 1], ach, 8, False, 'center')
        for i in range(nm):
            c = cells[2 + i]; cell_text(c, '', 8)
            if plan and plan[0] <= i <= plan[1]: shade(c, 'BDD7EE')
            if done and done[0] <= i <= done[1]: shade(c, '2F6DB5')
    set_col_widths(table, [1.0, 5.4] + [0.78] * nm + [1.6])
    lg = doc.add_table(rows=2, cols=2); lg.style = 'Table Grid'
    cell_text(lg.cell(0, 0), '', 8); shade(lg.cell(0, 0), 'BDD7EE'); cell_text(lg.cell(0, 1), '당초계획', 8)
    cell_text(lg.cell(1, 0), '', 8); shade(lg.cell(1, 0), '2F6DB5'); cell_text(lg.cell(1, 1), '개발실적(2026-09-23 초안 기준)', 8)
    set_col_widths(lg, [1.2, 5.0])

def build_docx(out_path):
    doc = Document()
    sec = doc.sections[0]
    sec.page_width = Cm(21.0); sec.page_height = Cm(29.7)
    sec.left_margin = sec.right_margin = Cm(2.0); sec.top_margin = Cm(2.0); sec.bottom_margin = Cm(1.8)
    st = doc.styles['Normal']; st.font.name = FONT; st.font.size = Pt(12)
    st.element.get_or_add_rPr().get_or_add_rFonts().set(qn('w:eastAsia'), FONT)
    for name, size in (('Heading 1', 15), ('Heading 2', 13), ('Heading 3', 12), ('Heading 4', 12)):
        hs = doc.styles[name]; hs.font.name = FONT; hs.font.size = Pt(size); hs.font.bold = True; hs.font.color.rgb = RGBColor(0, 0, 0)
        hs.element.get_or_add_rPr().get_or_add_rFonts().set(qn('w:eastAsia'), FONT)
    add_page_number(sec)
    z = doc.settings.element.find(qn('w:zoom'))
    if z is not None and z.get(qn('w:percent')) is None: z.set(qn('w:percent'), '100')
    for it in C:
        k = it[0]
        if k == 'cover': render_cover(doc)
        elif k == 'summary': render_summary(doc)
        elif k == 'toc': render_toc(doc)
        elif k == 'pb': doc.add_paragraph().add_run().add_break(WD_BREAK.PAGE)
        elif k in ('h1', 'h2', 'h3', 'h4'):
            lvl = int(k[1]); h = doc.add_heading(level=lvl); h.paragraph_format.space_before = Pt(14 if lvl <= 2 else 10); h.paragraph_format.space_after = Pt(6)
            txt = subst(it[1])
            if lvl == 3: txt = '▪ ' + txt
            elif lvl == 4: txt = '◦ ' + txt
            add_runs(h, txt, {1: 15, 2: 13, 3: 12, 4: 12}[lvl], True)
            for r in h.runs: r.font.color.rgb = RGBColor(0, 0, 0)
        elif k == 'p':
            t = subst(it[1]); para(doc, t, 12 if not t.startswith('   ·') else 11, align='justify', left=0.9 if t.startswith('   ·') else 0)
        elif k == 'b1': para(doc, 'ㅇ ' + subst(it[1]), 12, align='justify', left=0.6, first=-0.6)
        elif k == 'b2': para(doc, '- ' + subst(it[1]), 12, align='justify', left=1.2, first=-0.5)
        elif k == 'b3': para(doc, '▪ ' + subst(it[1]), 12, align='justify', left=1.8, first=-0.5)
        elif k == 'note': para(doc, subst(it[1]), 9, align='justify', after=3)
        elif k == 'table':
            d = it[1]
            if d['caption']: caption(doc, f"표 {tab_no[d['key']]} {subst(d['caption'])}")
            add_table(doc, [subst(h) for h in d['header']] if d['header'] else None, [[subst(str(v)) for v in r] for r in d['rows']], d['widths'], d['font'], d['header_rows'], d['align'], d['merges'])
            para(doc, '', 6, after=2)
        elif k == 'fig':
            d = it[1]; add_figure(doc, os.path.join(FIG_DIR, d['file']), d['width'], f"그림 {fig_no[d['key']]} {subst(d['caption'])}")
        elif k == 'gantt': render_gantt(doc, it[1])
    doc.save(out_path)

