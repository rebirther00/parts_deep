def set_font(run, size=None, bold=None, color=None):
    run.font.name = FONT
    rpr = run._element.get_or_add_rPr()
    rf = rpr.find(qn('w:rFonts'))
    if rf is None:
        rf = OxmlElement('w:rFonts'); rpr.append(rf)
    for a in ('w:ascii', 'w:hAnsi', 'w:eastAsia', 'w:cs'):
        rf.set(qn(a), FONT)
    if size: run.font.size = Pt(size)
    if bold is not None: run.font.bold = bold
    if color: run.font.color.rgb = RGBColor(*color)

INLINE = re.compile(r'(\*\*.+?\*\*|【.+?】)')
def add_runs(par, text, size, bold=False):
    for piece in INLINE.split(text):
        if not piece: continue
        if piece.startswith('**') and piece.endswith('**'):
            r = par.add_run(piece[2:-2]); set_font(r, size, True)
        elif piece.startswith('【') and piece.endswith('】'):
            r = par.add_run(piece); set_font(r, size, bold); r.font.highlight_color = WD_COLOR_INDEX.YELLOW
        else:
            r = par.add_run(piece); set_font(r, size, bold)

def para(doc, text, size=12, bold=False, align=None, left=0.0, first=0.0, before=0, after=4, line=1.15):
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.left_indent = Cm(left); pf.first_line_indent = Cm(first)
    pf.space_before = Pt(before); pf.space_after = Pt(after); pf.line_spacing = line
    if align == 'center': p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    elif align == 'justify': p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    add_runs(p, text, size, bold)
    return p

def shade(cell, fill):
    tcPr = cell._element.get_or_add_tcPr()
    old = tcPr.find(qn('w:shd'))
    if old is not None: tcPr.remove(old)
    shd = OxmlElement('w:shd'); shd.set(qn('w:val'), 'clear'); shd.set(qn('w:color'), 'auto'); shd.set(qn('w:fill'), fill)
    # 스키마 순서: ... tcBorders, shd, noWrap, tcMar, textDirection, tcFitText, vAlign, hideMark
    for tag in ('w:noWrap', 'w:tcMar', 'w:textDirection', 'w:tcFitText', 'w:vAlign', 'w:hideMark'):
        nxt = tcPr.find(qn(tag))
        if nxt is not None:
            nxt.addprevious(shd); return
    tcPr.append(shd)

def cell_text(cell, text, size=8, bold=False, align='left', fill=None):
    cell.text = ''
    lines = text.split('\n')
    for i, ln in enumerate(lines):
        p = cell.paragraphs[0] if i == 0 else cell.add_paragraph()
        p.paragraph_format.space_after = Pt(0); p.paragraph_format.space_before = Pt(0); p.paragraph_format.line_spacing = 1.0
        if align == 'center': p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        add_runs(p, ln, size, bold)
    cell.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER
    if fill: shade(cell, fill)

def set_col_widths(table, widths):
    table.autofit = False
    for row in table.rows:
        for i, w in enumerate(widths):
            if i < len(row.cells):
                row.cells[i].width = Cm(w)

def add_table(doc, header, rows, widths, font=8, header_rows=1, align=None, merges=()):
    ncol = len(header) if header else len(rows[0])
    table = doc.add_table(rows=(1 if header else 0) + len(rows), cols=ncol)
    table.style = 'Table Grid'; table.alignment = WD_TABLE_ALIGNMENT.CENTER
    r0 = 0
    if header:
        for j, h in enumerate(header):
            cell_text(table.rows[0].cells[j], h, font, True, 'center', 'D9D9D9' if header_rows else None)
        r0 = 1
    for i, row in enumerate(rows):
        for j, v in enumerate(row):
            a = 'center' if (align is None and j > 0 and len(str(v)) <= 14) else (align or 'left')
            cell_text(table.rows[r0 + i].cells[j], str(v), font, False, a)
    for (a, b, c, d) in merges:
        table.cell(a, b).merge(table.cell(c, d))
    if widths: set_col_widths(table, widths)
    return table

